class 合同错误(ValueError):
    """输入、版本、状态或输出违反固定合同时抛出。"""


def 文件指纹(路径: Path) -> str:
    摘要 = hashlib.sha256()
    try:
        with 路径.open("rb") as 文件:
            while 数据 := 文件.read(1024 * 1024):
                摘要.update(数据)
    except OSError as 异常:
        raise 合同错误(f"输入文件读取失败：{路径}") from 异常
    return 摘要.hexdigest()


def 要求键(对象: Any, 键集合: set[str], 名称: str) -> dict[str, Any]:
    if type(对象) is not dict or set(对象) != 键集合:
        raise 合同错误(f"{名称}字段漂移")
    return 对象


def 读取配置(路径: Path, 根目录: Path) -> dict[str, Any]:
    try:
        配置 = json.loads(路径.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as 异常:
        raise 合同错误("闭环配置不可读取") from 异常
    要求键(
        配置,
        {"合同版本", "标的", "主研究尺度", "事后结果观察窗口", "上游合并提交", "输入"},
        "配置",
    )
    if 配置["标的"] != list(标的顺序):
        raise 合同错误("前向标的必须严格为BTC、ETH")
    if 配置["主研究尺度"] != list(主研究尺度):
        raise 合同错误("主研究尺度漂移")
    if 配置["事后结果观察窗口"] != list(事后窗口):
        raise 合同错误("事后结果观察窗口漂移")
    if type(配置["输入"]) is not dict or len(配置["输入"]) != 7:
        raise 合同错误("输入合同必须包含七份上游证据")
    for 名称, 输入 in 配置["输入"].items():
        要求键(输入, {"路径", "SHA-256", "批次"}, f"输入.{名称}")
        相对路径 = Path(输入["路径"])
        路径 = (根目录 / 相对路径).resolve()
        if 根目录.resolve() not in 路径.parents or 路径.is_symlink() or not 路径.is_file():
            raise 合同错误(f"输入路径不在仓库内：{名称}")
        if 文件指纹(路径) != 输入["SHA-256"]:
            raise 合同错误(f"输入指纹不一致：{名称}")
        输入["_绝对路径"] = 路径
    return 配置


def 读取CSV(路径: Path, 期望表头: list[str], 名称: str) -> tuple[list[dict[str, str]], str]:
    开始指纹 = 文件指纹(路径)
    try:
        with 路径.open(encoding="utf-8-sig", newline="") as 文件:
            读取器 = csv.DictReader(文件)
            if list(读取器.fieldnames or []) != 期望表头:
                raise 合同错误(f"{名称}列合同漂移")
            行 = list(读取器)
    except (OSError, UnicodeError, csv.Error) as 异常:
        raise 合同错误(f"{名称}读取失败") from 异常
    if 文件指纹(路径) != 开始指纹:
        raise 合同错误(f"{名称}读取期间发生输入漂移")
    if not 行:
        raise 合同错误(f"{名称}没有记录")
    return 行, 开始指纹


def 精确批次(行: list[dict[str, str]], 字段: str, 预期: str, 名称: str) -> None:
    if {记录.get(字段, "") for 记录 in 行} != {预期}:
        raise 合同错误(f"{名称}批次或版本不一致")


def 唯一映射(
    行: list[dict[str, str]], 键字段: tuple[str, ...], 名称: str
) -> dict[tuple[str, ...], dict[str, str]]:
    结果: dict[tuple[str, ...], dict[str, str]] = {}
    for 记录 in 行:
        键 = tuple(记录.get(字段, "") for 字段 in 键字段)
        if any(not 值 for 值 in 键) or 键 in 结果:
            raise 合同错误(f"{名称}存在缺失或重复成员")
        结果[键] = 记录
    return 结果


def 记录指纹(记录: dict[str, str]) -> str:
    正文 = json.dumps(记录, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(正文.encode("utf-8")).hexdigest()


def 门状态(值: str, 通过值: set[str], 拒绝值: set[str] = set()) -> str:
    if 值 in 通过值:
        return "通过"
    if 值 in 拒绝值:
        return "拒绝"
    return "无法判定"


def 生成成员(
    配置: dict[str, Any],
    来源: dict[tuple[str, str], dict[str, str]],
    时间质量: dict[tuple[str, str], dict[str, str]],
    质量: dict[str, dict[str, str]],
    断档: dict[str, dict[str, str]],
    异常: dict[str, dict[str, str]],
    重放: dict[tuple[str, str], dict[str, str]],
    成本: dict[tuple[str, str], dict[str, str]],
    批次: str,
) -> tuple[list[dict[str, str]], dict[str, Any]]:
    资产集合 = sorted({键[0] for 键 in 来源})
    成员: list[dict[str, str]] = []
    for 标的 in 标的顺序:
        for 资产编号 in 资产集合:
            键 = (资产编号, 标的)
            身份 = 来源[键]
            时质 = 时间质量[键]
            重放行 = 重放[键]
            成本行 = 成本[键]
            质量行 = 质量[(资产编号,)]
            断档行 = 断档[(资产编号,)]
            异常行 = 异常[(资产编号,)]

            来源门 = 门状态(身份["状态"], {"已证明", "通过"}, {"拒绝", "失败"})
            时间门 = 门状态(时质["质量状态"], {"通过", "已证明"}, {"拒绝", "失败"})
            质量门 = 门状态(质量行["可用性结论"], {"可用", "通过"}, {"不可用", "拒绝", "失败"})
            if 断档行["断档状态"] in {"有断档", "拒绝", "失败"}:
                质量门 = "拒绝"
            if 异常行["严重度"] in {"高", "致命"} and 异常行["规则状态"] in {"已执行", "拒绝"}:
                质量门 = "拒绝"
            重放门 = 门状态(重放行["重放结论"], {"通过", "可重放"}, {"拒绝", "失败"})
            成本门 = 门状态(成本行["结论"], {"通过", "可用"}, {"拒绝", "不可用", "失败"})

            身份成员 = 身份["成员编号"]
            绑定一致 = all(
                (
                    时质["成员编号"] == 身份成员,
                    重放行["来源成员编号"] == 身份成员,
                    成本行["来源成员编号"] == 身份成员,
                    时质["输入成员SHA-256"] == 身份["输入成员SHA-256"],
                    重放行["来源成员指纹"] == 身份["身份记录SHA-256"],
                    重放行["输入清单指纹"] != "",
                    成本行["输入指纹"] != "",
                    重放行["标的"] == 标的,
                    成本行["标的"] == 标的,
                )
            )
            血缘门 = "通过" if 绑定一致 else "拒绝"
            门 = [来源门, 时间门, 质量门, 重放门, 成本门, 血缘门]
            if any(状态 in {"拒绝", "失败"} for 状态 in 门):
                最终 = "不可用"
            elif all(状态 == "通过" for 状态 in 门):
                最终 = "可用"
            else:
                最终 = "无法判定"
            原因 = ";".join(
                f"{名称}={状态}"
                for 名称, 状态 in zip(门名称, 门)
                if 状态 != "通过"
            ) or "六道门均通过"
            成员.append(
                {
                    "批次": 批次,
                    "资产编号": 资产编号,
                    "标的": 标的,
                    "来源成员编号": 身份成员,
                    "来源身份批次": 身份["来源身份批次"],
                    "来源身份状态": 身份["状态"],
                    "来源成员指纹": 身份["身份记录SHA-256"],
                    "时间质量批次": 时质["批次"],
                    "时间质量状态": 时质["质量状态"],
                    "质量内容指纹": 时质["内容指纹"],
                    "质量审计批次": 质量行["审计批次"],
                    "质量结论": 质量行["可用性结论"],
                    "断档状态": 断档行["断档状态"],
                    "异常状态": 异常行["规则状态"],
                    "重放批次": 重放行["验证批次"],
                    "重放结论": 重放行["重放结论"],
                    "成本批次": 成本行["验证批次"],
                    "成本结论": 成本行["结论"],
                    "门1来源身份": 来源门,
                    "门2时间与质量合同": 时间门,
                    "门3质量审计": 质量门,
                    "门4历史重放": 重放门,
                    "门5成本与执行": 成本门,
                    "门6血缘": 血缘门,
                    "最终状态": 最终,
                    "原因": 原因,
                    "解除条件": "；".join(
                        值
                        for 值 in (身份["解除条件"], 时质["解除条件"], 重放行["解除条件"], 成本行["解除条件"])
                        if 值
                    ),
                }
            )
    if len(成员) != len(资产集合) * len(标的顺序):
        raise 合同错误("双标的成员覆盖不守恒")
    计数 = {
        标的: dict(Counter(记录["最终状态"] for 记录 in 成员 if 记录["标的"] == 标的))
        for 标的 in 标的顺序
    }
    for 标的 in 标的顺序:
        if sum(计数[标的].values()) != len(资产集合):
            raise 合同错误("BTC/ETH计数不守恒")
    return 成员, {"候选总体": len(资产集合), "总成员数": len(成员), "最终状态计数": 计数}


def 写CSV(路径: Path, 行: list[dict[str, str]], 表头: list[str]) -> None:
    with 路径.open("w", encoding="utf-8", newline="") as 文件:
        写入器 = csv.DictWriter(文件, fieldnames=表头, lineterminator="\n")
        写入器.writeheader()
        写入器.writerows(行)


def 原子发布(暂存目录: Path, 目标目录: Path) -> None:
    if 目标目录.exists():
        raise 合同错误(f"批次目录已存在，禁止覆盖：{目标目录}")
    目标目录.parent.mkdir(parents=True, exist_ok=True)
    os.replace(暂存目录, 目标目录)


def 追加批次索引(路径: Path, 批次: str, 生成时间: str, 摘要: dict[str, Any]) -> None:
    """只追加批次索引；不重写既有行。"""
    表头 = ["批次", "生成时间", "候选总体", "总成员数", "BTC状态计数", "ETH状态计数"]
    路径.parent.mkdir(parents=True, exist_ok=True)
    新文件 = not 路径.exists()
    with 路径.open("a", encoding="utf-8", newline="") as 文件:
        写入器 = csv.DictWriter(文件, fieldnames=表头, lineterminator="\n")
        if 新文件:
            写入器.writeheader()
        写入器.writerow(
            {
                "批次": 批次,
                "生成时间": 生成时间,
                "候选总体": 摘要["候选总体"],
                "总成员数": 摘要["总成员数"],
                "BTC状态计数": json.dumps(摘要["最终状态计数"]["BTC"], ensure_ascii=False, sort_keys=True),
                "ETH状态计数": json.dumps(摘要["最终状态计数"]["ETH"], ensure_ascii=False, sort_keys=True),
            }
        )


